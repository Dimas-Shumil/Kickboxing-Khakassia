import {scopedDatabase} from './gym-scope.js';
import createFinanceRouter from '../routes/finances.routes.js';
import createAccessRouter from '../routes/access.routes.js';
import createGymRouter from '../routes/gym.routes.js';
import createAnalyticsRouter from '../routes/analytics.routes.js';
import createSiteAdminRouter from '../routes/site-content.routes.js';
import createPublicSiteRouter,{sitePreviewRouter} from '../routes/public-site.routes.js';
import createCompetitionsRouter from '../routes/competitions.routes.js';
import createHistoryRouter from '../routes/history.routes.js';
import createPublicHistoryRouter,{historyPreviewRouter} from '../routes/public-history.routes.js';
import createPublicCompetitionsRouter,{competitionPreviewRouter} from '../routes/public-competitions.routes.js';
import express from 'express';
import createPeopleRouter from '../routes/people.routes.js';
import createPublicPeopleRouter,{peoplePreviewRouter} from '../routes/public-people.routes.js';
import createPublicNewsRouter from '../routes/public-news.routes.js';
import cookieParser from 'cookie-parser';
import helmet from 'helmet';
import path from 'node:path';
import {readdirSync} from 'node:fs';
import {securityConfig} from '../config/security.js';
import {createSessionService} from '../services/session.service.js';
import {createRequireAuth} from '../middleware/require-auth.js';
import {createValidateOrigin} from '../middleware/validate-origin.js';
import createAuthRouter from '../routes/auth.routes.js';
import createDashboardRouter from '../routes/dashboard.routes.js';
import createStudentsRouter from '../routes/students.routes.js';
import createPaymentsRouter from '../routes/payments.routes.js';
import createNewsRouter from '../routes/news.routes.js';
import createHeartbeatRouter from '../routes/session-heartbeat.routes.js';
import createAdminPagesRouter from '../routes/admin-pages.routes.js';
import {asyncHandler} from './http.js';
function createApp(db,config){
 db=scopedDatabase(db);
 const app=express();app.disable('x-powered-by');if(process.env.TRUST_PROXY)app.set('trust proxy',process.env.TRUST_PROXY);
 app.use(helmet({contentSecurityPolicy:false,crossOriginEmbedderPolicy:false,strictTransportSecurity:config.production?undefined:false}));
 app.use(cookieParser());app.use(express.json({limit:'256kb'}));
 const security=securityConfig(config),sessions=createSessionService(db,security),requireAuth=createRequireAuth(db,security),validateOrigin=createValidateOrigin(config);
 const ctx={db,config,security,sessions,requireAuth,validateOrigin};
 const noStore=(_req,res,next)=>{res.set({'Cache-Control':'no-store','Pragma':'no-cache','X-Robots-Tag':'noindex, nofollow'});next();};
 app.use('/api/admin',noStore);
 app.use('/admin',noStore,(_req,res,next)=>{res.set('Content-Security-Policy',"default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; font-src 'self' https://fonts.gstatic.com; img-src 'self' data:; object-src 'none'; frame-ancestors 'none'; base-uri 'self'; form-action 'self'");next();});
 app.use('/api/admin/auth',createAuthRouter(ctx));
 app.use('/api/admin/session/heartbeat',createHeartbeatRouter(ctx));
 app.use('/api/admin/dashboard',createDashboardRouter(ctx));
 app.use('/api/admin/analytics',createAnalyticsRouter(ctx));
 app.use('/api/admin/students',createStudentsRouter(ctx));
 app.use('/api/admin/payments',createPaymentsRouter(ctx));
 app.use('/api/admin/gym',createGymRouter(ctx));
 app.use('/api/admin/finances',createFinanceRouter(ctx));
 app.use('/api/admin/access',createAccessRouter(ctx));
 app.use('/api/admin/news',createNewsRouter(ctx));
 app.use('/api/admin/people',createPeopleRouter(ctx));
 app.use('/api/admin/competitions',createCompetitionsRouter(ctx));
 app.use('/api/admin/history',createHistoryRouter(ctx));
 app.use('/api/admin/site',createSiteAdminRouter(ctx));
 app.use('/api/admin',(_req,res)=>res.status(404).json({success:false,message:'Метод API не найден.'}));
 app.use('/admin',peoplePreviewRouter(ctx));
 app.use('/admin',competitionPreviewRouter(ctx));
 app.use('/admin',historyPreviewRouter(ctx));
 app.use('/admin',sitePreviewRouter(ctx));
 app.use('/admin',createAdminPagesRouter(ctx));
 app.use('/admin-pages',(req,res)=>{const name=path.basename(req.path).replace(/\.html$/,'');res.redirect(302,'/admin/'+(['dashboard','activity','gym','groups','group','trainings','training','attendance','students','student','payments','payment','news','news-edit','news-preview','people','person-edit','person-preview','competitions','competition-edit','competition-preview','history','history-edit','history-preview','site-pages','site-page-edit','site-documents','site-document-edit','site-media','login'].includes(name)?name:'dashboard')+(req.url.includes('?')?'?'+req.url.split('?')[1]:''));});
 app.get('/health',(_req,res)=>res.json({success:true,message:'Federation server is running'}));
 app.get('/health/live',(_req,res)=>res.json({status:'ok'}));
 app.get('/health/ready',asyncHandler(async(_req,res)=>{await db.adminSession.count();res.json({status:'ok'});}));
 app.use('/site',express.static(path.join(config.ROOT,'site'),{index:false}));
 app.use('/components',express.static(path.join(config.ROOT,'components'),{index:false}));
 // Only known public HTML pages have canonical aliases; unknown paths remain 404.
 const publicDir=path.join(config.ROOT,'public');
 const pages=new Set(readdirSync(publicDir).filter(name=>name.endsWith('.html')).map(name=>name.slice(0,-5)));
 app.use((req,res,next)=>{
  if(!['GET','HEAD'].includes(req.method))return next();
  const match=/^\/(?:public\/)?([a-z0-9-]+?)(?:\.html)?\/?$/.exec(req.path);
  const query=req.originalUrl.includes('?')?req.originalUrl.slice(req.originalUrl.indexOf('?')):'';
  if(req.path==='/public/'||req.path==='/public')return res.redirect(301,'/'+query);
  if(!match||!pages.has(match[1]))return next();
  const canonical=match[1]==='index'?'/':'/'+match[1];
  if(req.path!==canonical)return res.redirect(301,canonical+query);
  return next();
 });
 app.use(createPublicPeopleRouter(ctx));
 app.use(createPublicNewsRouter(ctx));
 app.use(createPublicCompetitionsRouter(ctx));
 app.use(createPublicHistoryRouter(ctx));
 app.use(createPublicSiteRouter(ctx));
 for(const page of pages)if(page!=='index')app.get('/'+page,(_req,res)=>res.sendFile(path.join(publicDir,page+'.html')));
 app.use(express.static(publicDir,{index:false,extensions:false}));
 app.use((_req,res)=>res.status(404).sendFile(path.join(config.ROOT,'public/404.html')));
 app.use((err,req,res,_next)=>{const status=err.status||(err.type==='entity.too.large'?413:500),message=status>=500?'Не удалось подтвердить выполнение действия. Проверьте запись перед повторной отправкой.':err.message;if(status>=500)console.error('Request failed:',err.code||err.name);if(req.path.startsWith('/api/'))return res.status(status).json({success:false,message});res.status(status).type('text').send(message);});
 return app;
}
export {createApp};
